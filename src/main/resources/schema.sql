CREATE TABLE IF NOT EXISTS users (
    user_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(200) NOT NULL,
    email VARCHAR(200) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS requests (
    id_request INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description VARCHAR(200) NOT NULL,
    user_id INTEGER NOT NULL REFERENCES users ON DELETE CASCADE,
    crated TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS items (
    item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES users ON DELETE CASCADE,
    name VARCHAR(200) NOT NULL,
    description VARCHAR(200) NOT NULL,
    available BOOLEAN NOT NULL,
    id_request INTEGER REFERENCES requests ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS bookings (
    booking_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id INTEGER NOT NULL REFERENCES items ON DELETE CASCADE,
    data_start TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    data_end TIMESTAMP WITHOUT TIME ZONE NOT NULL CHECK (data_end > data_start),
    user_id INTEGER NOT NULL REFERENCES users ON DELETE CASCADE,
    status VARCHAR(10) NOT NULL CHECK (status IN ('WAITING', 'APPROVED', 'REJECTED', 'CANCELED'))
);

CREATE TABLE IF NOT EXISTS comments (
    comment_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    text VARCHAR(255) NOT NULL,
    item_id INTEGER NOT NULL REFERENCES items ON DELETE CASCADE,
    user_id INTEGER NOT NULL REFERENCES users ON DELETE CASCADE,
    created TIMESTAMP WITHOUT TIME ZONE NOT NULL
);
